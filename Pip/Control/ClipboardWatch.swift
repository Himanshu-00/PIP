import AppKit

/// Offers to summarise long copied text (40+ words). Polls `changeCount`
/// (the pasteboard has no notification); skips concealed/transient items
/// and Pip's own copies. Nothing stored; the offer expires in 20 s.
@MainActor
final class ClipboardWatch: ObservableObject {

    static let shared = ClipboardWatch()

    struct Offer: Equatable {
        let text: String
        let words: Int
        /// Came over Universal Clipboard from an iPhone or iPad.
        let fromPhone: Bool
        let at: Date
    }

    /// A long copy waiting to be summarised. Nil once used or expired.
    @Published private(set) var offer: Offer?
    /// Called with each new offer, to flash it in the notch.
    var onOffer: ((Offer) -> Void)?

    private static let enabledKey = "pipClipboardOffers"
    static var isEnabled: Bool {
        get { UserDefaults.standard.object(forKey: enabledKey) as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    private static let minimumWords = 40
    private static let lifetime: TimeInterval = 20

    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var expiry: DispatchWorkItem?

    private init() {}

    func start() {
        guard timer == nil else { return }
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.25          // lets macOS batch the wakeup with others
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        clear()
    }

    /// Hands over the waiting text (once) and clears the offer.
    func take() -> Offer? {
        guard let offer, Date().timeIntervalSince(offer.at) < Self.lifetime else { clear(); return nil }
        clear()
        return offer
    }

    func clear() {
        expiry?.cancel()
        expiry = nil
        if offer != nil { offer = nil }
    }

    /// Password managers and one-time codes mark their copies; those are
    /// never read. Also used by Pip's `read_clipboard`.
    static func isPrivate(_ board: NSPasteboard) -> Bool {
        let types = Set(board.types?.map(\.rawValue) ?? [])
        return !types.isDisjoint(with: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"])
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != lastCount else { return }
        lastCount = board.changeCount
        guard Self.isEnabled else { return }

        let types = Set(board.types?.map(\.rawValue) ?? [])
        guard !Self.isPrivate(board) else { return }
        // Pip's own copies.
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier != ProcessInfo.processInfo.processIdentifier
        else { return }
        guard let text = board.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty else { return }
        let words = text.split(whereSeparator: { $0.isWhitespace }).count
        guard words >= Self.minimumWords else { return }

        let offer = Offer(text: text, words: words,
                          fromPhone: types.contains("com.apple.is-remote-clipboard"), at: Date())
        self.offer = offer
        ActivityLog.write(.system, "long copy noticed: \(words) words\(offer.fromPhone ? " from iPhone" : "")")
        onOffer?(offer)

        expiry?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated { self?.clear() }
        }
        expiry = work
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.lifetime, execute: work)
    }
}
